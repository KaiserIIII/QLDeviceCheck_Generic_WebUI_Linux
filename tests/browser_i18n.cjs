const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { chromium } = require('playwright');
(async()=>{
  const base=process.argv[2]||'http://127.0.0.1:18336';
  const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHANNEL?{channel:process.env.PLAYWRIGHT_CHANNEL}:{})});
  const page=await browser.newPage({locale:'en-US',viewport:{width:1440,height:980}}), errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  try {
    await page.goto(base);
    await page.getByLabel('Interface language').selectOption('en',{timeout:2000});
    await page.getByRole('button',{name:'New inspection',exact:true}).click();
    const station='工位 <script>window.injected=true</script> & unchanged', operator='工程师原文';
    await page.getByLabel('Station / equipment ID').fill(station);
    await page.getByLabel('Operator',{exact:true}).fill(operator);
    await page.getByLabel('Inspection notes').fill('原始备注 <b>raw</b>');
    await page.locator('#language-switch').selectOption('zh');
    await page.getByLabel('工位 / 设备编号').waitFor();
    assert.equal(await page.getByLabel('工位 / 设备编号').inputValue(),station);
    await page.locator('#language-switch').selectOption('en');
    await page.getByLabel('Demo scenario').selectOption('faults');
    await page.getByRole('button',{name:'Create inspection task',exact:true}).click();
    await page.getByTestId('task-state').filter({hasText:'Completed'}).waitFor();
    const baseline=await page.getByTestId('task-state').getAttribute('data-job-id');
    assert.ok((await page.locator('main').innerText()).includes(station));
    assert.equal(await page.evaluate(()=>window.injected),undefined);
    await page.getByRole('button',{name:'View evidence',exact:true}).first().click();
    await page.getByRole('dialog',{name:'Device test evidence',exact:true}).waitFor();
    assert.ok((await page.locator('#evidence-body').innerText()).includes('SIMULATED'));
    await page.getByRole('button',{name:'Close evidence',exact:true}).click();
    const downloaded=page.waitForEvent('download');
    await page.getByRole('button',{name:'Export HTML',exact:true}).click();
    const report=await fs.readFile(await (await downloaded).path(),'utf8');
    assert.ok(report.includes('lang="en"'));
    assert.ok(report.includes('Industrial device acceptance report'));
    assert.ok(report.includes('工程师原文'));
    assert.ok(report.includes('&lt;script&gt;'));
    await page.getByLabel('Retest scenario').selectOption('healthy');
    await page.getByRole('button',{name:'Retest devices that did not pass',exact:true}).click();
    await page.getByTestId('task-state').filter({hasText:'Completed'}).waitFor();
    const current=await page.getByTestId('task-state').getAttribute('data-job-id');
    await page.getByRole('button',{name:'Compare with original task',exact:true}).click();
    await page.getByTestId('comparison').filter({hasText:'Recovered'}).waitFor();
    await page.locator('#language-switch').selectOption('zh');
    await page.getByTestId('comparison').filter({hasText:'恢复'}).waitFor();
    await page.locator('#language-switch').selectOption('en');
    for(const [nav,title] of [['Station overview','Make every inspection traceable.'],['Device catalog','Expected device catalog'],['Configuration validation','Validate device configuration'],['Task history','Task history']]){
      await page.getByRole('button',{name:nav,exact:true}).click();
      await page.getByRole('heading',{name:title,exact:true}).waitFor();
      if(nav==='Configuration validation'){
        await page.getByRole('button',{name:'Load current configuration',exact:true}).click();
        const config=await page.getByLabel('Device configuration JSON').inputValue();
        await page.locator('#language-switch').selectOption('zh');
        await page.getByLabel('设备配置 JSON').waitFor();
        assert.equal(await page.getByLabel('设备配置 JSON').inputValue(),config);
        await page.locator('#language-switch').selectOption('en');
        await page.getByRole('button',{name:'Validate configuration',exact:true}).click();
        await page.locator('#validation').filter({hasText:'"valid": true'}).waitFor();
      }
    }
    await page.getByLabel('Search records').fill('工位');
    await page.getByLabel('Execution status').selectOption('completed');
    await page.getByLabel('Time order').selectOption('oldest');
    await page.getByLabel('Baseline task').selectOption(baseline);
    await page.getByLabel('Current task').selectOption(current);
    await page.locator('#language-switch').selectOption('zh');
    await page.getByLabel('搜索记录').waitFor();
    assert.equal(await page.getByLabel('搜索记录').inputValue(),'工位');
    assert.equal(await page.getByLabel('执行状态').inputValue(),'completed');
    assert.equal(await page.getByLabel('时间排序').inputValue(),'oldest');
    assert.equal(await page.getByLabel('基线任务').inputValue(),baseline);
    assert.equal(await page.getByLabel('当前任务').inputValue(),current);
    await page.getByRole('button',{name:'比较任务',exact:true}).click();
    await page.getByTestId('comparison').waitFor();
    await page.locator('#language-switch').selectOption('en');
    await page.reload();
    await page.getByRole('button',{name:'New inspection',exact:true}).waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'),'en');
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'Task history',exact:true}).click();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await fs.mkdir('output/playwright',{recursive:true});
    await page.screenshot({path:'output/playwright/i18n-mobile-en.png',fullPage:true});
    await page.goto(base+'/legacy');
    await page.getByRole('heading',{name:'Industrial device diagnostics',exact:true}).waitFor();
    await page.getByRole('button',{name:'Scan devices',exact:true}).waitFor();
    await page.getByRole('button',{name:'Test all',exact:true}).waitFor();
    await page.locator('#language-switch').selectOption('zh');
    await page.getByRole('heading',{name:'工控机设备检测',exact:true}).waitFor();
    await page.locator('#language-switch').selectOption('en');
    await page.getByRole('button',{name:'Access token',exact:true}).click();
    await page.locator('#accessToken').fill('unchanged-secret');
    await page.evaluate(()=>QLI18N.setLanguage('zh'));
    assert.equal(await page.locator('#accessToken').inputValue(),'unchanged-secret');
    await page.locator('#credentialsCancel').click();
    await page.locator('#language-switch').selectOption('en');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({path:'output/playwright/i18n-legacy-mobile-en.png',fullPage:true});
    const blocked=await browser.newPage();
    blocked.on('pageerror',e=>errors.push(e.message));
    await blocked.addInitScript(()=>Object.defineProperty(window,'localStorage',{get(){throw Error('blocked');}}));
    await blocked.goto(base);
    await blocked.locator('#language-switch').selectOption('en');
    await blocked.getByRole('button',{name:'New inspection',exact:true}).click();
    await blocked.locator('#language-switch').selectOption('zh');
    await blocked.getByLabel('工位 / 设备编号').waitFor();
    await blocked.close();
    assert.deepEqual(errors,[]);
    console.log('PASS: bilingual workflow, exports, form/filter/selection retention, legacy, reload, blocked storage, 390px layout');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
